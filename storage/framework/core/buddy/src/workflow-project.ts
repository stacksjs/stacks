import type { WorkflowConfig, WorkflowStep } from '@stacksjs/types'
import { execFileSync } from 'node:child_process'
import { appendFileSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { pathToFileURL } from 'node:url'
import { nativeReleaseSecretNames, nativeWorkflowSecretNames, renderReviewOsWorkflow, validateWorkflowConfig } from './workflow-template'

export async function loadWorkflowConfig(root: string): Promise<WorkflowConfig> {
  const file = join(root, 'config/workflows.ts')
  if (!existsSync(file)) throw new Error('Configure config/workflows.ts before running a workflow')
  const config = (await import(pathToFileURL(file).href)).default as WorkflowConfig
  validateWorkflowConfig(config)
  return config
}

function requireWorkflowSecrets(names: string[], phase: string, env: Record<string, string | undefined>): void {
  const missing = [...new Set(names)].filter(name => !env[name]?.trim())
  if (missing.length) throw new Error(`Missing workflow credentials for ${phase}: ${missing.join(', ')}. Configure these names in the ios-testflight environment. Values are never printed.`)
}

/** Check scoped inputs before expensive native builds, without revealing values. */
export async function checkNativeWorkflowCredentials(root: string, phase: string, env: Record<string, string | undefined> = process.env): Promise<void> {
  if (!['native-accept', 'native-release'].includes(phase)) throw new Error('Choose native-accept or native-release credentials')
  const config = await loadWorkflowConfig(root)
  if (!config.native) throw new Error('Configure a native workflow before checking its credentials')
  if (phase === 'native-release' && !config.release) throw new Error('Configure native release metadata before checking release credentials')
  requireWorkflowSecrets(phase === 'native-release' ? nativeReleaseSecretNames(config) : nativeWorkflowSecretNames(config, 'native-accept'), phase, env)
}

function ownedFile(root: string, file: string): string {
  const path = resolve(root, file)
  const child = relative(realpathSync(root), realpathSync(path))
  if (!child || isAbsolute(child) || child === '..' || child.startsWith(`..${sep}`) || lstatSync(path).isSymbolicLink() || !lstatSync(path).isFile()) throw new Error('Workflow inputs must be regular files inside the project')
  return path
}

export function workflowReleaseIdentity(root: string, config: NonNullable<WorkflowConfig['release']>): { version: string, build: number, tag: string } {
  const manifest = JSON.parse(readFileSync(ownedFile(root, config.versionFile), 'utf8'))
  const version = manifest[config.versionField ?? 'version']
  const build = manifest[config.buildField ?? 'build']
  if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version) || !Number.isSafeInteger(build) || build <= 0) throw new Error('The release manifest needs a semantic version and a positive integer build')
  return { version, build, tag: `v${version}-build.${build}` }
}

export function writeProjectWorkflow(root: string, config: WorkflowConfig, force = false): string {
  const file = join(root, '.reviewos/workflows/ci.yml')
  const source = renderReviewOsWorkflow(config)
  if (existsSync(file) && !readFileSync(file, 'utf8').startsWith('# Generated by buddy workflow:setup') && !force) throw new Error('The workflow already exists. Review it before replacing it with --force')
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, source)
  return file
}

function downloadedArtifact(root: string, config: WorkflowConfig): string {
  if (!config.native) throw new Error('Configure the native artifact before acceptance')
  const directory = resolve(root, config.native.downloadDirectory)
  const files = [...new Bun.Glob(config.native.archivePattern).scanSync({ cwd: directory, absolute: true, onlyFiles: true, followSymlinks: false })]
  if (files.length !== 1) throw new Error('Native acceptance needs exactly one downloaded application archive')
  return ownedFile(root, files[0]!)
}

/** Execute argv directly; an artifact path or a title is never shell code. */
export async function runWorkflowStep(root: string, step: WorkflowStep): Promise<void> {
  const config = await loadWorkflowConfig(root)
  if (!['prepare', 'lint', 'typecheck', 'test', 'build', 'deploy', 'after-deploy', 'native-build', 'native-accept', 'native-sign', 'native-upload', 'native-verify', 'native-cleanup'].includes(step)) throw new Error('Unknown workflow step')
  requireWorkflowSecrets(nativeWorkflowSecretNames(config, step), step, process.env)
  const defaults: Partial<Record<WorkflowStep, string[][]>> = {
    prepare: existsSync(join(root, 'pantry.lock')) ? [['pantry', 'ci']] : [],
    lint: [['./buddy', 'lint']], typecheck: [['./buddy', 'typecheck']], test: [['./buddy', 'test']],
    build: [[process.execPath, 'run', 'build']], deploy: [['./buddy', 'deploy', '--prod', '--yes']],
  }
  const commands = config.commands?.[step] ?? defaults[step]
  if (!commands && !(step === 'native-cleanup' && !config.release)) throw new Error(`Configure the ${step} workflow command`)
  for (const command of commands ?? []) {
    const argv = command.map(value => value === '{artifact}' ? downloadedArtifact(root, config) : value)
    const child = Bun.spawn(argv, { cwd: root, env: process.env, stdout: 'inherit', stderr: 'inherit', stdin: 'ignore' })
    const code = await child.exited
    if (code !== 0) throw new Error(`The ${step} workflow command exited ${code}`)
  }
}

/** Mirror event payloads need not contain commit messages; inspect Git itself. */
export async function writeWorkflowReleaseState(root: string): Promise<boolean> {
  const config = await loadWorkflowConfig(root)
  const git = (...args: string[]) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim()
  const requested = process.env.WORKFLOW_UPLOAD_REQUESTED === 'true'
  const release = git('log', '-1', '--format=%s').startsWith('chore(release): v')
  let upload = false
  if (requested || release) {
    if (!config.release) throw new Error('Configure release metadata before uploading')
    const identity = workflowReleaseIdentity(root, config.release)
    const branch = config.branch ?? 'main'
    const main = process.env.GITHUB_REF ? process.env.GITHUB_REF === `refs/heads/${branch}` : git('branch', '--show-current') === branch
    let tagged = false
    try { tagged = git('rev-parse', '--verify', '--quiet', `${identity.tag}^{commit}`) === git('rev-parse', 'HEAD') }
    catch { /* No tag is an ordinary unpublished candidate, not an upload. */ }
    if (!main || !tagged) throw new Error('An upload needs its actual release tag on the configured main branch')
    if (git('status', '--porcelain', '--untracked-files=no')) throw new Error('An upload needs the unchanged release checkout')
    upload = true
  }
  if (!process.env.GITHUB_OUTPUT) throw new Error('The workflow must provide its step output file')
  appendFileSync(process.env.GITHUB_OUTPUT, `upload=${upload}\n`)
  return upload
}
