import { afterEach, beforeEach, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { readGenerationConfig } from '@stacksjs/actions/daemon/generation-config'
import { prepareCommitApproval, reviewGeneratedCommit } from '../src/generation-approval'
import { git } from '../src/generation-changes'

const imports = 'storage/framework/auto-imports/functions.ts'
const jobs = 'storage/framework/auto-imports/jobs.ts'
const migration = 'database/migrations/1777777777-approval.sql'
const manual = 'database/migrations/1777777778-manual.sql'
const marker = '-- qb:generated\n-- @generated by `buddy migrate:regenerate` - edits will be overwritten\n'
const tasks = ['imports', 'migrations'] as const
const stacksHome = process.env.STACKS_HOME
let path: string
let root: string

function write(file: string, content: string): void {
  const target = join(root, file)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, content)
}

beforeEach(() => {
  path = mkdtempSync(join(tmpdir(), 'buddy-approval-test-'))
  root = join(path, 'app')
  process.env.STACKS_HOME = join(path, 'stacks')
  mkdirSync(root)
  git(root, 'init', '--initial-branch=main')
  git(root, 'config', 'user.name', 'Buddy Test')
  git(root, 'config', 'user.email', 'buddy@example.test')
  git(root, 'config', 'commit.gpgSign', 'false')
  git(root, 'config', 'core.hooksPath', '/dev/null')
  write('.gitignore', '*.sql\n')
  write('config/buddy.json', JSON.stringify({
    generation: { enabled: true, autoCommit: true, commitApproval: true, types: false },
  }))
  write(imports, 'export const previous = true\n')
  write(jobs, 'export const previousJob = true\n')
  write('source.ts', 'const previous = true\n')
  git(root, 'add', '.')
  git(root, 'commit', '-m', 'Initial')
})

afterEach(() => {
  if (stacksHome === undefined)
    delete process.env.STACKS_HOME
  else
    process.env.STACKS_HOME = stacksHome
  rmSync(path, { recursive: true, force: true })
})

test('notification only proposes clean-before generated paths and approval commits exactly the reviewed tree', async () => {
  expect(readGenerationConfig(root)?.autoCommit).toBe(false)
  const head = git(root, 'rev-parse', 'HEAD')
  write(jobs, 'export const preexistingEdit = true\n')
  write('source.ts', 'const staged = true\n')
  git(root, 'add', 'source.ts')
  write('source.ts', 'const unstaged = true\n')
  const index = git(root, 'diff', '--cached')
  const notifications: number[] = []
  const notify = (_root: string, count: number) => notifications.push(count)

  const proposeImports = prepareCommitApproval(root, ['imports'], [...tasks], notify)
  write(imports, 'export const newBarrel = true\n')
  write(jobs, 'export const overwrittenPreexistingEdit = true\n')
  proposeImports!()
  const proposeMigrations = prepareCommitApproval(root, ['migrations'], [...tasks], notify)
  write(migration, `${marker}CREATE TABLE sample (id INTEGER);\n`)
  write(manual, 'CREATE TABLE manual (id INTEGER);\n')
  proposeMigrations!()
  const refresh = prepareCommitApproval(root, [...tasks], [...tasks], notify)
  refresh!()
  expect(notifications).toEqual([1, 2])
  expect(git(root, 'rev-parse', 'HEAD')).toBe(head)
  expect(git(root, 'diff', '--cached')).toBe(index)

  let reviewed = ''
  expect(await reviewGeneratedCommit(root, async (diff) => {
    reviewed = diff
    expect(diff).toContain(imports)
    expect(diff).toContain(migration)
    expect(diff).not.toContain(manual)
    expect(diff).not.toContain(jobs)
    expect(diff).not.toContain('source.ts')
    return false
  })).toBe('pending')
  expect(git(root, 'rev-parse', 'HEAD')).toBe(head)
  expect(git(root, 'diff', '--cached')).toBe(index)

  const commit = await reviewGeneratedCommit(root, async (diff) => {
    expect(diff).toBe(reviewed)
    return true
  })
  expect(git(root, 'rev-parse', 'HEAD').trim()).toBe(commit)
  expect(git(root, 'diff', '--binary', 'HEAD^', 'HEAD')).toBe(reviewed)
  expect(git(root, 'diff', '--cached')).toBe(index)
  expect(git(root, 'diff', '--', 'source.ts')).toContain('const unstaged = true')
  expect(git(root, 'status', '--short', '--', imports, migration)).toBe('')
  expect(await reviewGeneratedCommit(root, async () => true)).toBe('empty')
})

test('changes during review or disabling approval require fresh consent', async () => {
  const head = git(root, 'rev-parse', 'HEAD')
  const propose = prepareCommitApproval(root, ['imports'], [...tasks], () => {})
  write(imports, 'export const generated = true\n')
  propose!()

  await expect(reviewGeneratedCommit(root, async () => {
    write(imports, 'export const manualEditAfterReview = true\n')
    return true
  })).rejects.toThrow('The proposal changed')
  expect(git(root, 'rev-parse', 'HEAD')).toBe(head)
  expect(git(root, 'diff', '--cached')).toBe('')
  expect(git(root, 'diff')).toContain('manualEditAfterReview')

  const rerun = prepareCommitApproval(root, ['imports'], [...tasks], () => {})
  rerun!()
  expect(await reviewGeneratedCommit(root, async () => true)).toBe('empty')

  write(imports, 'export const previous = true\n')
  const proposeAgain = prepareCommitApproval(root, ['imports'], [...tasks], () => {})
  write(imports, 'export const regenerated = true\n')
  proposeAgain!()
  await expect(reviewGeneratedCommit(root, async () => {
    write('config/buddy.json', '{"generation":{"enabled":true}}')
    return true
  })).rejects.toThrow('The proposal changed')
  expect(git(root, 'rev-parse', 'HEAD')).toBe(head)
})
