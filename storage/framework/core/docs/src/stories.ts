import { createHash, randomUUID } from 'node:crypto'
import { createReadStream } from 'node:fs'
import { copyFile, lstat, mkdir, open, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises'
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { pathToFileURL } from 'node:url'
import { version } from '../package.json'

export type StoryPlatform = 'browser' | 'ios' | 'android'
export interface StorySession<Context = unknown> {
  context: Context
  /** Capture the current display, after all scene assertions have completed. */
  screenshot: () => Promise<Uint8Array>
  /** Finalize the recording at the exact videoPath passed to open. */
  finish: () => Promise<void>
  /** Dispose only resources this session owns. Must be safe after finish fails. */
  close: () => Promise<void>
}
export interface StoryDriver<Context = unknown> {
  platform: StoryPlatform
  /** Configuration included in freshness hashes, never printed to reports. */
  fingerprint?: unknown
  open: (options: { videoPath: string, fps: number, signal: AbortSignal }) => Promise<StorySession<Context>>
}
export interface StoryScene<Context = unknown> {
  id: string
  title: string
  description?: string
  /** Existing E2E actions and assertions belong here. Throwing fails the scene. */
  run: (context: Context, signal: AbortSignal) => Promise<void> | void
  holdMs?: number
  timeoutMs?: number
}
export interface Story<Context = any> {
  id: string
  title: string
  description?: string
  driver: StoryDriver<Context>
  scenes: StoryScene<Context>[]
}
export interface StoryConfig {
  stories: Story[]
  /** Generated docs directory: pages, index and manifest. Default docs/stories. */
  outDir?: string
  /**
   * BunPress public media directory: videos and scene pictures move here, one
   * copy each. Default sibling public/<output folder>. False disables
   * publishing and keeps the media beside the pages in outDir.
   */
  publishDir?: string | false
  title?: string
  fps?: number
  holdMs?: number
  timeoutMs?: number
  /** Extra files that must remain unchanged for --check to pass. */
  inputs?: string[]
}
export function defineStoryConfig(config: StoryConfig): StoryConfig { return config }
export function defineStory<Context>(story: Story<Context>): Story<Context> { return story }
export interface StoryArtifact { path: string, sha256: string, bytes: number }
export interface StorySceneResult { id: string, title: string, description?: string, status: 'passed' | 'failed' | 'not-run', startedMs?: number, endedMs?: number, screenshot?: StoryArtifact }
export interface StoryResult { id: string, title: string, description?: string, platform: StoryPlatform, status: 'passed' | 'failed' | 'not-run', scenes: StorySceneResult[], video?: StoryArtifact, page?: StoryArtifact }
export interface StoryReport {
  version: 1
  configHash: string
  runId?: string
  inventory: { id: string, title: string, platform: StoryPlatform, scenes: { id: string, title: string }[] }[]
  results: StoryResult[]
  index?: StoryArtifact
  outDir: string
  mediaDir?: string
  published?: StoryArtifact[]
}
export interface RecordStoryOptions {
  config?: string
  root?: string
  outDir?: string
  only?: string[]
  list?: boolean
  check?: boolean
  signal?: AbortSignal
  onProgress?: (result: StoryResult) => void
  /** Trusted diagnostics hook. Errors can contain secrets; never publish them verbatim. */
  onError?: (error: unknown, storyId: string) => void
}
const owner = 'stacks-story-recordings-v1\n'
const generated = '<!-- Generated by buddy docs:stories. -->'
const hash = (bytes: string | Uint8Array) => createHash('sha256').update(bytes).digest('hex')
const safeId = (value: string) => typeof value === 'string' && /^[a-z0-9][a-z0-9-]{0,79}$/.test(value)
function text(value: string): string { return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replace(/[\r\n]/g, ' ').replace(/([\\`*_[\]#|])/g, '\\$1') }
async function exists(path: string) { try { await lstat(path); return true } catch (error: any) { if (error.code === 'ENOENT') return false; throw error } }
async function plainPath(path: string, boundary = path) {
  let current = resolve(path)
  while (true) {
    if (await exists(current)) {
      if ((await lstat(current)).isSymbolicLink()) throw new Error(`Story output cannot traverse a symbolic link: ${current}`)
    }
    if (current === resolve(boundary)) return
    const parent = dirname(current)
    if (parent === current) return
    current = parent
  }
}
async function artifact(root: string, path: string): Promise<StoryArtifact> {
  await plainPath(path, root)
  const stat = await lstat(path)
  if (!stat.isFile() || stat.size === 0) throw new Error(`Missing or empty story artifact: ${path}`)
  const digest = createHash('sha256')
  let bytes = 0
  for await (const chunk of createReadStream(path)) { digest.update(chunk); bytes += chunk.length }
  return { path: relative(root, path).split(sep).join('/'), sha256: digest.digest('hex'), bytes }
}
function asset(root: string, value: StoryArtifact): string {
  const path = resolve(root, value.path)
  if (!value.path || isAbsolute(value.path) || relative(root, path).startsWith('..')) throw new Error('Story artifact escaped its output directory')
  return path
}
/** A folder inside the project, as the manifest records it: relative and with forward slashes. One outside stays absolute. */
export function portablePath(root: string, path: string): string {
  const inside = relative(root, path)
  return inside && !inside.startsWith('..') && !isAbsolute(inside) ? inside.split(sep).join('/') : path
}
async function validate(config: StoryConfig) {
  if (!config || !Array.isArray(config.stories) || !config.stories.length) throw new Error('Story configuration needs at least one story')
  const ids = new Set<string>()
  const timing = (value: number, min: number, max: number, name: string) => { if (!Number.isInteger(value) || value < min || value > max) throw new Error(`Invalid story ${name}`) }
  timing(config.fps ?? 12, 1, 60, 'fps (1 to 60)')
  timing(config.holdMs ?? 700, 0, 30000, 'holdMs (0 to 30000)')
  timing(config.timeoutMs ?? 120000, 100, 1800000, 'timeoutMs (100 to 1800000)')
  for (const story of config.stories) {
    if (!safeId(story.id) || ids.has(story.id) || !story.title?.trim()) throw new Error(`Invalid or duplicate story id/title: ${story.id}`)
    ids.add(story.id)
    if (!['browser', 'ios', 'android'].includes(story.driver?.platform) || typeof story.driver.open !== 'function') throw new Error(`Invalid driver for story ${story.id}`)
    if (!Array.isArray(story.scenes) || !story.scenes.length) throw new Error(`Story ${story.id} has no scenes`)
    const scenes = new Set<string>()
    for (const scene of story.scenes) {
      if (!safeId(scene.id) || scenes.has(scene.id) || !scene.title?.trim() || typeof scene.run !== 'function') throw new Error(`Invalid or duplicate scene in ${story.id}: ${scene.id}`)
      scenes.add(scene.id)
      timing(scene.holdMs ?? config.holdMs ?? 700, 0, 30000, 'scene holdMs')
      timing(scene.timeoutMs ?? config.timeoutMs ?? 120000, 100, 1800000, 'scene timeoutMs')
    }
  }
}
function render(result: StoryResult, prefix: string): string {
  const lines = [generated, `# ${text(result.title)}`, '', result.description ? text(result.description) : '', '', `Platform: ${result.platform}. Result: **${result.status}**.`, '']
  if (result.video) lines.push(`<video controls playsinline preload="metadata" src="${prefix}${result.video.path}" poster="${result.scenes.find(scene => scene.screenshot)?.screenshot ? prefix + result.scenes.find(scene => scene.screenshot)!.screenshot!.path : ''}"></video>`, '', `[Download video](${prefix}${result.video.path})`, '')
  for (const scene of result.scenes) {
    lines.push(`## ${text(scene.title)}`, '', `Result: **${scene.status}**.${scene.startedMs === undefined ? '' : ` Starts at ${(scene.startedMs / 1000).toFixed(1)}s.`}`, '', scene.description ? text(scene.description) : '', '')
    if (scene.screenshot) lines.push(`![${text(scene.title)}](${prefix}${scene.screenshot.path})`, '')
    else lines.push('No screenshot was captured for this scene.', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

/** Record configured journeys, then atomically publish their docs and hashed evidence. */
export async function recordStories(options: RecordStoryOptions = {}): Promise<StoryReport> {
  if (options.list && options.check) throw new Error('Choose --list or --check')
  const root = await realpath(resolve(options.root ?? process.cwd()))
  const configPath = resolve(root, options.config ?? 'config/stories.ts')
  const configBytes = await readFile(configPath)
  const config: StoryConfig = (await import(`${pathToFileURL(configPath).href}?story=${hash(configBytes)}`)).default
  await validate(config)
  const fingerprints = [version, hash(configBytes), hash(JSON.stringify(config, (_, value) => typeof value === 'function' ? value.toString() : value))]
  for (const input of [...(config.inputs ?? [])].sort()) fingerprints.push(`${input}:${hash(await readFile(resolve(root, input)))}`)
  const outDir = resolve(root, options.outDir ?? config.outDir ?? 'docs/stories')
  const mediaDir = config.publishDir === false ? undefined : resolve(root, config.publishDir ?? join(dirname(outDir), 'public', basename(outDir)))
  if (mediaDir && (mediaDir === outDir || !relative(outDir, mediaDir).startsWith('..') || !relative(mediaDir, outDir).startsWith('..'))) throw new Error('Published media must have a separate directory outside the story output')
  if (outDir === root || relative(outDir, root) === '' || (!relative(outDir, root).startsWith('..') && !isAbsolute(relative(outDir, root)))) throw new Error('Story output must not contain the project root')
  const report: StoryReport = {
    version: 1, configHash: hash(fingerprints.join('\n')), outDir, mediaDir,
    inventory: config.stories.map(story => ({ id: story.id, title: story.title, platform: story.driver.platform, scenes: story.scenes.map(({ id, title }) => ({ id, title })) })),
    results: config.stories.map(story => ({ id: story.id, title: story.title, description: story.description, platform: story.driver.platform, status: 'not-run', scenes: story.scenes.map(scene => ({ id: scene.id, title: scene.title, description: scene.description, status: 'not-run' })) })),
  }
  const selected = new Set(options.only ?? config.stories.map(story => story.id))
  if (!selected.size || [...selected].some(id => !config.stories.some(story => story.id === id))) throw new Error('Unknown or empty story selection')
  if (options.list) return report
  await plainPath(outDir)
  if (options.check) {
    await plainPath(join(outDir, '.stacks-stories'))
    if (await readFile(join(outDir, '.stacks-stories'), 'utf8') !== owner) throw new Error('Unowned story output')
    const saved: StoryReport = JSON.parse(await readFile(join(outDir, 'manifest.json'), 'utf8'))
    if (saved.version !== 1 || saved.configHash !== report.configHash || JSON.stringify(saved.inventory) !== JSON.stringify(report.inventory)) throw new Error('Story recordings are stale')
    if (!saved.index || saved.results.length !== report.results.length || saved.results.some((result, index) => result.id !== report.results[index]!.id || result.status !== 'passed' || !result.video || !result.page || result.scenes.length !== report.results[index]!.scenes.length || result.scenes.some((scene, i) => scene.id !== report.results[index]!.scenes[i]!.id || scene.status !== 'passed' || !scene.screenshot))) throw new Error('Story recordings are incomplete or failed')
    // Pages and the index live in the output; videos and pictures live where
    // they are published, or in the output when publishing is off.
    const media = saved.results.flatMap(result => [result.video!, ...result.scenes.map(scene => scene.screenshot!)])
    const pages = [saved.index, ...saved.results.map(result => result.page!)]
    for (const value of mediaDir ? pages : [...pages, ...media]) {
      const actual = await artifact(outDir, asset(outDir, value))
      if (actual.sha256 !== value.sha256 || actual.bytes !== value.bytes) throw new Error(`Story artifact changed: ${value.path}`)
    }
    if (mediaDir) {
      await plainPath(mediaDir)
      await plainPath(join(mediaDir, '.stacks-stories'))
      if (await readFile(join(mediaDir, '.stacks-stories'), 'utf8') !== owner || !saved.published?.length) throw new Error('Published story media is incomplete')
      if (JSON.stringify(saved.published) !== JSON.stringify(media)) throw new Error('Published story media inventory changed')
      for (const value of media) {
        const actual = await artifact(mediaDir, asset(mediaDir, value))
        if (actual.sha256 !== value.sha256 || actual.bytes !== value.bytes) throw new Error(`Published story media changed: ${value.path}`)
      }
    }
    return { ...saved, outDir, mediaDir }
  }
  if (await exists(outDir)) {
    await plainPath(join(outDir, '.stacks-stories'))
    if (!await exists(join(outDir, '.stacks-stories')) || await readFile(join(outDir, '.stacks-stories'), 'utf8') !== owner) throw new Error(`Refusing to overwrite an unowned story directory: ${outDir}`)
  }
  else {
    await mkdir(outDir, { recursive: true })
    await writeFile(join(outDir, '.stacks-stories'), owner, { flag: 'wx' })
  }
  const lock = await open(join(outDir, '.recording.lock'), 'wx', 0o600).catch(() => { throw new Error('Story output is locked by another recording; inspect .recording.lock before removing a stale lock') })
  await lock.writeFile(`${process.pid}\n`)
  const runId = `${new Date().toISOString().replaceAll(/[:.]/g, '-')}-${randomUUID()}`
  report.runId = runId
  const runDir = join(outDir, 'runs', runId)
  const controller = new AbortController()
  const abort = () => controller.abort(options.signal?.reason ?? new Error('Story recording interrupted'))
  process.once('SIGINT', abort); process.once('SIGTERM', abort)
  options.signal?.addEventListener('abort', abort, { once: true })
  if (options.signal?.aborted) abort()
  try {
    await plainPath(runDir, outDir)
    await mkdir(runDir, { recursive: true })
    for (const [index, story] of config.stories.entries()) {
      if (!selected.has(story.id)) continue
      const result = report.results[index]!
      const directory = join(runDir, story.id)
      await mkdir(directory)
      let session: StorySession | undefined
      let started = performance.now()
      try {
        controller.signal.throwIfAborted()
        session = await story.driver.open({ videoPath: join(directory, 'video.mp4'), fps: config.fps ?? 12, signal: controller.signal })
        started = performance.now()
        result.status = 'passed'
        for (const [sceneIndex, scene] of story.scenes.entries()) {
          controller.signal.throwIfAborted()
          const sceneResult = result.scenes[sceneIndex]!
          sceneResult.startedMs = Math.round(performance.now() - started)
          sceneResult.status = 'failed'
          let passed = false
          const timeout = setTimeout(() => controller.abort(new Error('Story scene timed out')), scene.timeoutMs ?? config.timeoutMs ?? 120000)
          try {
            await new Promise<void>((resolve, reject) => {
              const fail = () => reject(controller.signal.reason)
              controller.signal.addEventListener('abort', fail, { once: true })
              Promise.resolve().then(() => scene.run(session!.context, controller.signal)).then(resolve, reject).finally(() => controller.signal.removeEventListener('abort', fail))
              if (controller.signal.aborted) fail()
            })
            await new Promise<void>((resolve, reject) => {
              const fail = () => { clearTimeout(timer); reject(controller.signal.reason) }
              const timer = setTimeout(() => { controller.signal.removeEventListener('abort', fail); resolve() }, scene.holdMs ?? config.holdMs ?? 700)
              controller.signal.addEventListener('abort', fail, { once: true })
              if (controller.signal.aborted) fail()
            })
            passed = true
          }
          finally {
            clearTimeout(timeout)
            const screenshot = await session.screenshot()
            if (screenshot.length < 8 || Buffer.from(screenshot.subarray(0, 8)).toString('hex') !== '89504e470d0a1a0a') throw new Error('Driver did not produce a PNG screenshot')
            const path = join(directory, `${scene.id}.png`)
            await writeFile(path, screenshot, { flag: 'wx' })
            sceneResult.screenshot = await artifact(outDir, path)
            sceneResult.status = passed ? 'passed' : 'failed'
            sceneResult.endedMs = Math.round(performance.now() - started)
          }
        }
      }
      catch (error) {
        // Error strings can contain passwords, URLs or typed fixture values.
        // Keep public reports deliberately value-free. Assertions still fail the command.
        result.status = 'failed'
        options.onError?.(error, story.id)
      }
      finally {
        if (session) {
          try { await session.finish(); result.video = await artifact(outDir, join(directory, 'video.mp4')) }
          catch (error) { result.status = 'failed'; options.onError?.(error, story.id) }
          try { await session.close() } catch (error) { result.status = 'failed'; options.onError?.(error, story.id) }
        }
      }
      const page = join(directory, 'index.md')
      await writeFile(page, render(result, '../../../'), { flag: 'wx' })
      result.page = await artifact(outDir, page)
      options.onProgress?.(result)
      if (controller.signal.aborted) break
    }
    if (mediaDir) {
      await plainPath(mediaDir)
      if (await exists(mediaDir)) {
        await plainPath(join(mediaDir, '.stacks-stories'))
        if (await readFile(join(mediaDir, '.stacks-stories'), 'utf8') !== owner) throw new Error('Refusing to overwrite unowned published story media')
      }
      else { await mkdir(mediaDir, { recursive: true }); await writeFile(join(mediaDir, '.stacks-stories'), owner, { flag: 'wx' }) }
      report.published = report.results.flatMap(result => [result.video, ...result.scenes.map(scene => scene.screenshot)].filter((value): value is StoryArtifact => Boolean(value)))
      // Move, not copy: the pages link to the published files, and a second
      // copy in the output doubles every video a repository commits.
      for (const value of report.published) {
        const source = asset(outDir, value)
        const destination = asset(mediaDir, value)
        await plainPath(destination, mediaDir)
        await mkdir(dirname(destination), { recursive: true })
        if (await exists(destination)) throw new Error(`Published story media already exists: ${value.path}`)
        await rename(source, destination).catch(async (error: NodeJS.ErrnoException) => {
          if (error.code !== 'EXDEV') throw error
          await copyFile(source, destination, 1) // COPYFILE_EXCL, unique run paths only.
          await rm(source)
        })
      }
    }
    const indexPath = join(outDir, 'index.md')
    const manifestPath = join(outDir, 'manifest.json')
    for (const path of [indexPath, manifestPath]) {
      if (await exists(path)) {
        await plainPath(path)
        if (path === indexPath && !(await readFile(path, 'utf8')).startsWith(generated)) throw new Error('Refusing to replace a hand-written story index')
        if (path === manifestPath && JSON.parse(await readFile(path, 'utf8')).version !== 1) throw new Error('Refusing to replace an unknown story manifest')
      }
    }
    const indexPage = [generated, `# ${text(config.title ?? 'User stories')}`, '', 'Videos and screenshots from automated end-to-end journeys.', '', ...report.results.flatMap(result => [`- ${result.page ? `[${text(result.title)}](${result.page.path})` : text(result.title)} (${result.platform}): **${result.status}**`, ''])].join('\n')
    const indexStage = join(runDir, 'index.md.tmp')
    await writeFile(indexStage, indexPage, { flag: 'wx' })
    report.index = { path: 'index.md', sha256: hash(indexPage), bytes: Buffer.byteLength(indexPage) }
    const manifestStage = join(runDir, 'manifest.json.tmp')
    // The committed manifest names its folders from the project root, so it
    // reads the same on every machine; the returned report keeps full paths.
    const portable = { ...report, outDir: portablePath(root, outDir), mediaDir: mediaDir && portablePath(root, mediaDir) }
    await writeFile(manifestStage, `${JSON.stringify(portable, null, 2)}\n`, { flag: 'wx' })
    await rename(indexStage, indexPath)
    await rename(manifestStage, manifestPath)
    return report
  }
  finally {
    process.removeListener('SIGINT', abort); process.removeListener('SIGTERM', abort)
    options.signal?.removeEventListener('abort', abort)
    await lock.close()
    await rm(join(outDir, '.recording.lock'))
  }
}
