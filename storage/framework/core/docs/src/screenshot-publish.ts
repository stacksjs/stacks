/** A walkthrough video and a documentation page made from captured screens. */
import { openBrowserFilm, serveFilmStudio } from './browser-film'
import { captureBrowser } from './capture-browser'
import type { ScreenshotReport, ScreenshotResult, ScreenshotViewport } from './screenshots'
import { createHash } from 'node:crypto'
import { lstat, mkdir, readFile, rename } from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, resolve } from 'node:path'

export interface ScreenshotFilmOptions {
  /** How long each screen stays visible. Default 2 seconds, from 0.2 to 30. */
  secondsPerScreen?: number
  /** Output frame rate. Default 12, from 1 to 60. */
  fps?: number
  /** Only these configured viewports. Default: one film per viewport. */
  viewports?: string[]
}
export interface ScreenshotDocsOptions {
  /** Project-relative Markdown page to write, e.g. `docs/screens.md`. */
  page: string
  /** URL the output directory is served from, e.g. `/screens` for `docs/public/screens`. */
  base: string
  title?: string
  description?: string
}
export interface ScreenshotFilm { viewport: string, file: string, sha256: string, screens: number, seconds: number }
export interface ScreenshotDocsPage { path: string, sha256: string }

export const generatedScreensPage = '<!-- Generated by buddy docs:screenshots. Edit config/screenshots.ts instead. -->'
const hash = (bytes: string | Uint8Array): string => createHash('sha256').update(bytes).digest('hex')
const html = (value: string): string => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
const markdown = (value: string): string => html(value).replace(/[\r\n]+/g, ' ').replace(/([\\`*_[\]#|])/g, '\\$1')

export function validateScreenshotPublishing(film: ScreenshotFilmOptions | false | undefined, docs: ScreenshotDocsOptions | undefined, root: string, viewports: ScreenshotViewport[]): void {
  if (film) {
    const seconds = film.secondsPerScreen ?? 2
    if (!Number.isFinite(seconds) || seconds < 0.2 || seconds > 30) throw new Error('film.secondsPerScreen must be between 0.2 and 30')
    if (!Number.isInteger(film.fps ?? 12) || (film.fps ?? 12) < 1 || (film.fps ?? 12) > 60) throw new Error('film.fps must be an integer from 1 to 60')
    for (const name of film.viewports ?? []) if (!viewports.some(viewport => viewport.name === name)) throw new Error(`Unknown film viewport: ${name}`)
  }
  if (docs) {
    const page = resolve(root, docs.page)
    if (isAbsolute(docs.page) || relative(root, page).startsWith('..') || !docs.page.endsWith('.md')) throw new Error('docs.page must be a Markdown file inside the project')
    if (!/^\/[\w./-]*$/.test(docs.base) || docs.base.includes('..')) throw new Error('docs.base must be a site path such as /screens')
  }
}

/**
 * One MP4 per viewport: every captured screen in inventory order, held for a
 * readable moment. The capture's own browser encodes it, so nothing else has
 * to be installed.
 */
export async function filmScreenshots(output: string, results: ScreenshotResult[], viewports: ScreenshotViewport[], options: ScreenshotFilmOptions, backend: 'webkit' | 'chrome' = process.platform === 'darwin' ? 'webkit' : 'chrome'): Promise<ScreenshotFilm[]> {
  const films: ScreenshotFilm[] = []
  const seconds = options.secondsPerScreen ?? 2
  const fps = options.fps ?? 12
  const hold = Math.max(1, Math.round(seconds * fps))
  const browser = captureBrowser(backend)
  const room = serveFilmStudio()
  try {
    for (const viewport of viewports) {
      if (options.viewports?.length && !options.viewports.includes(viewport.name)) continue
      const frames = results.filter(result => result.status === 'captured' && result.file && result.viewport.name === viewport.name)
      if (!frames.length) continue
      // A page per film: the encoder and its canvas are sized for one viewport.
      let bytes: Uint8Array
      let view: Bun.WebView | undefined
      try {
        view = await browser.view(320, 240)
        const frameView = view
        await frameView.navigate(room.url)
        const film = await openBrowserFilm(script => frameView.evaluate(script), { fps, width: viewport.width, height: viewport.height })
        for (const frame of frames) await film.add(new Uint8Array(await readFile(join(output, frame.file!))), hold)
        bytes = await film.finish()
      }
      catch (error) { throw new Error(`The ${viewport.name} screens could not be filmed: ${error instanceof Error ? error.message.slice(0, 400) : 'the browser failed'}`) }
      finally { view?.close() }
      const file = `film-${viewport.name}.mp4`
      await Bun.write(join(output, `${file}.tmp`), bytes)
      await rename(join(output, `${file}.tmp`), join(output, file))
      films.push({ viewport: viewport.name, file, sha256: hash(bytes), screens: frames.length, seconds: frames.length * hold / fps })
    }
    return films
  }
  finally {
    try { await browser.close() }
    finally { room.stop() }
  }
}

/** The page readers open: the films, then every screen with its explanation and pictures. */
export function renderScreensPage(report: Pick<ScreenshotReport, 'results' | 'inventory' | 'generatorVersion'> & { films?: ScreenshotFilm[] }, options: ScreenshotDocsOptions): string {
  const base = options.base.replace(/\/+$/, '')
  const title = options.title ?? 'Screens'
  const captured = report.results.filter(result => result.status === 'captured' && result.file)
  const lines = ['---', `title: ${JSON.stringify(title)}`, `description: ${JSON.stringify(options.description ?? 'Every screen of the application, captured automatically from its views.')}`, '---', '', generatedScreensPage, '', `# ${markdown(title)}`, '', `${new Set(captured.map(result => result.id)).size} of ${report.inventory.length} screens, captured automatically from the application's views with @stacksjs/docs ${report.generatorVersion}. A new view appears here after the next capture.`, '']
  for (const film of report.films ?? []) {
    const poster = captured.find(result => result.viewport.name === film.viewport)
    lines.push(`## Walkthrough video (${markdown(film.viewport)})`, '', `<video controls playsinline preload="none" src="${html(`${base}/${film.file}`)}"${poster ? ` poster="${html(`${base}/${poster.file}`)}"` : ''} style="width:100%;max-width:${poster && poster.viewport.width < 600 ? poster.viewport.width : 1100}px;height:auto"></video>`, '', `${film.screens} screens in ${Math.round(film.seconds)} seconds. [Download the video](${base}/${film.file}).`, '')
  }
  const group = (path: string): string => path.split('/').filter(Boolean)[0]?.replace(/^[[:].*/, 'profiles') ?? 'home'
  const groups = new Map<string, typeof report.inventory>()
  for (const screen of report.inventory) groups.set(group(screen.path), [...(groups.get(group(screen.path)) ?? []), screen])
  const missing: string[] = []
  for (const [name, screens] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const body: string[] = []
    for (const screen of screens) {
      const shots = captured.filter(result => result.id === screen.id)
      if (!shots.length) {
        const result = report.results.find(row => row.id === screen.id)
        missing.push(`- ${markdown(screen.title)} (\`${screen.path}\`): ${screen.skip ? markdown(screen.skip) : result ? 'the last capture failed.' : 'not captured yet.'}`)
        continue
      }
      body.push(`### ${markdown(screen.title)}`, '', markdown(shots[0]!.description), '', ...(shots[0]!.reason ? [markdown(shots[0]!.reason), ''] : []), `Address: \`${screen.path}\``, '')
      for (const shot of shots) {
        body.push('<figure>', `  <img src="${html(`${base}/${shot.file}`)}" alt="${html(`${shot.title}, ${shot.viewport.name}`)}" width="${shot.viewport.width}" height="${shot.viewport.height}" loading="lazy" style="display:block;width:100%;max-width:${shot.viewport.width}px;height:auto">`, `  <figcaption>${html(shot.viewport.name)}, ${shot.viewport.width} by ${shot.viewport.height}${shot.profile === 'default' ? '' : `, signed in as ${html(shot.profile)}`}</figcaption>`, '</figure>', '')
      }
    }
    if (body.length) lines.push(`## ${markdown(name[0]!.toUpperCase() + name.slice(1).replace(/[-_]+/g, ' '))}`, '', ...body)
  }
  if (missing.length) lines.push('## Not pictured', '', 'These screens are part of the application and have no picture here.', '', ...missing, '')
  return `${lines.join('\n').trimEnd()}\n`
}

export async function writeScreensPage(root: string, report: Parameters<typeof renderScreensPage>[0], options: ScreenshotDocsOptions): Promise<ScreenshotDocsPage> {
  const file = resolve(root, options.page)
  try {
    if ((await lstat(file)).isSymbolicLink() || !(await readFile(file, 'utf8')).includes(generatedScreensPage)) throw new Error(`Refusing to replace a hand-written page: ${options.page}`)
  }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error }
  const page = renderScreensPage(report, options)
  await mkdir(dirname(file), { recursive: true })
  await Bun.write(`${file}.tmp`, page)
  await rename(`${file}.tmp`, file)
  return { path: options.page, sha256: hash(page) }
}
