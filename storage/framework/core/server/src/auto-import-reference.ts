export interface AutoImportGroup {
  source: string
  names: readonly string[]
}

export interface BrowserAutoImportSurface {
  runtime: readonly string[]
  macros: readonly string[]
  demand: readonly string[]
}

/** Read the installed compiler's delivery registries, never its ambient types. */
export async function browserAutoImportSurface(): Promise<BrowserAutoImportSurface | undefined> {
  try {
    const [runtime, demand, caching] = await Promise.all([
      import('@stacksjs/stx/runtime-globals'),
      import('@stacksjs/stx/unresolved-identifiers'),
      import('@stacksjs/stx/caching'),
    ])
    const source = await caching.getCachedSignalsRuntime(false)
    const aliases = [...source.matchAll(/window\.([A-Za-z_$][\w$]*)\s*=/g)]
      .map(match => match[1]!)
      .filter(name => !name.startsWith('__') && !name.startsWith('$'))
    return {
      runtime: [...new Set([...runtime.STX_RUNTIME_GLOBALS, ...aliases])],
      macros: runtime.COMPILE_TIME_ONLY_GLOBALS,
      demand: demand.SERVER_ONLY_COMPOSABLES,
    }
  }
  catch {
    // Older or server-only installations may not expose these registries.
    // An unavailable inventory must never turn into a guessed list of globals.
    return undefined
  }
}

function names(values: readonly string[]): string {
  return [...new Set(values)].sort().map(name => `\`${name}\``).join(', ') || '(none)'
}

/** Compact, deterministic reference read on demand by the bundled AI skills. */
export function renderAutoImportReference(server: readonly AutoImportGroup[], browser?: BrowserAutoImportSurface): string {
  const lines = [
    '# Available auto-imports',
    '',
    '<!-- Generated by buddy generate:auto-imports. Edit runtime sources, then regenerate. -->',
    '',
    'Use these names without imports in the context listed below. This project reference',
    'is refreshed by buddy generate, buddy generate:types and buddy generate:auto-imports.',
    'Read only the relevant section; package exports outside these lists need imports.',
    '',
    '## Server after Stacks boot',
    '',
    'Available in actions, routes, jobs, controllers and server-rendered templates after',
    'injectGlobalAutoImports completes. Standalone scripts, tests and framework packages',
    'that do not boot Stacks use explicit imports. Type-only exports always need type imports.',
    'Models may require an enabled feature or database readiness for operations.',
    'App definitions override defaults; explicit app-model imports retain exact inference.',
    'If boot reports a failed package or barrel, its names are unavailable until it loads.',
    '',
    '| Runtime source | Names available without imports |',
    '| --- | --- |',
    ...server.filter(group => group.names.length).map(group => `| ${group.source} | ${names(group.names)} |`),
    '',
    'Platform globals keep their built-in meaning. Import colliding app exports explicitly.',
    '',
    '## STX client scripts',
    '',
    'These names belong to `<script client>` and component client scripts. A TypeScript',
    'module imported by a client script declares its own imports; template bindings do',
    'not leak into module scope. Server helpers and resources/functions exports are not',
    'automatically browser globals. Bare STX helpers can differ from imported Stacks APIs;',
    'read stacks-composables/BROWSER.md for signatures before using them.',
    '',
  ]

  if (browser) {
    const macros = new Set(browser.macros)
    const runtime = new Set(browser.runtime)
    lines.push(
      '### Runtime and compiler bindings',
      '',
      names(browser.runtime.filter(name => !macros.has(name))),
      '',
      '### Compiler macros',
      '',
      names(browser.macros),
      '',
      '### Demand-delivered calls',
      '',
      'The installed STX compiler emits these helpers when it detects an authored call.',
      'Call them directly in the client script; do not assume an unused helper exists on window.',
      '',
      names(browser.demand.filter(name => !runtime.has(name))),
      '',
    )
  }
  else {
    lines.push('Installed STX delivery registries are unavailable. Check the installed STX',
      'runtime/compiler before omitting browser imports; ambient declarations are insufficient.', '',
    )
  }

  return lines.join('\n')
}
