import type { IosMobileConfig, MobileCrashReportingConfig } from '@stacksjs/types'
import { chmodSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Keep native source package-owned while retaining Xcode metadata for cloud project discovery. */
export function writeIosShellSupport(output: string, config: IosMobileConfig, bunVersion = Bun.version, crashReporting?: MobileCrashReportingConfig): void {
  const version = config.shell?.bunVersion ?? bunVersion
  if (!/^\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/.test(version)) throw new Error('ios.shell.bunVersion must be a Bun version such as 1.3.14')
  writeFileSync(join(output, '.gitignore'), '# Native sources are restored from the locked Craft package.\n*.swift\n')
  const scripts = join(output, 'ci_scripts')
  mkdirSync(scripts, { recursive: true })
  // Restoring build output does not boot the app or load its runtime preloader.
  writeFileSync(join(scripts, 'bunfig.toml'), 'preload = []\n')
  const path = join(scripts, 'ci_post_clone.sh')
  writeFileSync(path, `#!/bin/sh
set -eu
PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="\${CI_PRIMARY_REPOSITORY_PATH:-$(git -C "$PROJECT_DIR" rev-parse --show-toplevel)}"
if ! command -v bun >/dev/null 2>&1; then
  curl -fsSL https://bun.com/install -o /tmp/stacks-install-bun.sh
  bash /tmp/stacks-install-bun.sh "bun-v${version}"
  export PATH="$HOME/.bun/bin:$PATH"
fi
cd "$ROOT"
bun install --frozen-lockfile
bun --config="$PROJECT_DIR/ci_scripts/bunfig.toml" -e 'import { restoreIosShell } from "@stacksjs/mobile/testing"; restoreIosShell(process.argv[1])' "$PROJECT_DIR"
`)
  chmodSync(path, 0o755)
  writeDsymUpload(scripts, crashReporting)
}

/**
 * `ci_post_xcodebuild.sh`: after Xcode Cloud archives the app, upload its
 * dSYMs to bughq so the build's crashes symbolicate.
 *
 * bughq runs on Linux, which can neither read a dSYM's DWARF in Apple's
 * layout nor demangle Swift, so the Mac that built the app reduces each dSYM
 * with `/usr/bin/symbols` (every function and line range, demangled) and
 * uploads that, gzipped. The upload token is a secret: an Xcode Cloud
 * environment variable, never the app's config. Without one the script says
 * so and exits 0, because a missing upload must not fail a release.
 */
export function renderDsymUpload(host: string): string {
  return `#!/bin/sh
# Generated by buddy build:ios from config/mobile.ts crashReporting.
set -u
[ "\${CI_XCODEBUILD_ACTION:-}" = "archive" ] || exit 0
if [ -z "\${BUGHQ_UPLOAD_TOKEN:-}" ]; then
  echo "bughq: BUGHQ_UPLOAD_TOKEN is not set in this workflow, so no dSYMs were uploaded and this build's crashes will show addresses."
  exit 0
fi
HOST="\${BUGHQ_HOST:-${host}}"
for DSYM in "\${CI_ARCHIVE_PATH}"/dSYMs/*.dSYM; do
  [ -d "$DSYM" ] || continue
  OUT="\${TMPDIR:-/tmp}/bughq-$(basename "$DSYM").symbols.gz"
  if symbols -arch arm64 "$DSYM" 2>/dev/null | gzip -c > "$OUT"; then
    if curl -fsS --retry 3 -X POST "$HOST/api/debug-files?kind=apple" \\
      -H "Authorization: Bearer $BUGHQ_UPLOAD_TOKEN" -H "Content-Type: application/octet-stream" \\
      --data-binary @"$OUT"; then
      echo "bughq: uploaded $(basename "$DSYM")"
    else
      echo "bughq: could not upload $(basename "$DSYM")"
    fi
  fi
  rm -f "$OUT"
done
exit 0
`
}

function writeDsymUpload(scripts: string, crashReporting: MobileCrashReportingConfig | undefined): void {
  const path = join(scripts, 'ci_post_xcodebuild.sh')
  if (!crashReporting?.key || crashReporting.uploadSymbols === false) {
    rmSync(path, { force: true })
    return
  }
  writeFileSync(path, renderDsymUpload(crashReporting.host ?? 'https://bughq.org'))
  chmodSync(path, 0o755)
}
