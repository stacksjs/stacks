/**
 * The named routes this application registers, as a runtime map.
 *
 * `url('email.unsubscribe', …)` names a route with a string, and a typo throws
 * when the URL is built - in a mail job at 3am, not at the call site.
 *
 * This is the ONE name in the framework that cannot be derived from what is on
 * disk. Every other one - actions, listeners, policies, middleware classes,
 * jobs, models, tables - comes from a map the resolver reads, so `keyof` and
 * the resolution cannot disagree. A route name is different in kind: it is
 * produced by RUNNING code. It is attached by a chained `.name()` whose path
 * may have come from a group prefix, so a static read of the source would have
 * to re-implement the router to know what `/users/{id}` a given
 * `.name('users.show')` actually got.
 *
 * So the route table is loaded and the answer written out - as a runtime value
 * under `storage/framework/auto-imports/`, alongside the other name maps, NOT
 * as a declaration file. `storage/framework/types/registries.d.ts` reads it
 * with `typeof import(...)`.
 */

import { existsSync } from 'node:fs'
import { log } from '@stacksjs/logging'
import { path as p } from '@stacksjs/path'
import { storage } from '@stacksjs/storage'

/**
 * Every named route, as `name → path`.
 *
 * Read from the live route table rather than by scanning source, because a
 * name is attached by a chained `.name()` call whose path may have come from a
 * group prefix - a static scan would have to re-implement the router to know
 * what `/users/{id}` a given `.name('users.show')` actually got. Loading the
 * routes is the same thing the OpenAPI generator does, and for the same reason.
 *
 * Best-effort on purpose. A route registry that fails to load leaves the
 * `routes` key out entirely, which falls back to "any name" - the behaviour
 * before this existed. Refusing to generate types because one route file threw
 * would be a much worse trade than an unchecked `url()`.
 */
async function collectNamedRoutes(): Promise<Record<string, string>> {
  const registryFile = p.appPath('Routes.ts')
  if (!existsSync(registryFile))
    return {}

  try {
    const { listNamedRoutes, loadRoutes } = await import('@stacksjs/router')
    const { default: routeRegistry } = await import(registryFile) as { default: Parameters<typeof loadRoutes>[0] }
    await loadRoutes(routeRegistry)
    return listNamedRoutes()
  }
  catch (error) {
    log.debug('[generate:types] Could not load routes for named-route types', { error })
    return {}
  }
}

/**
 * Write `storage/framework/auto-imports/routes.ts`.
 *
 * A RUNTIME map, not a declaration file. Every other name in the framework -
 * actions, listeners, policies, middleware classes, jobs, models, tables - is
 * derived from a map the resolver reads, so `keyof` and the resolution can
 * never disagree. Route names could not join them, because a route name is
 * produced by RUNNING code: it is attached by a chained `.name()` whose path
 * may have come from a group prefix, and no static read of the source can know
 * what `/users/{id}` a given `.name('users.show')` actually got.
 *
 * So this loads the route table, exactly as the OpenAPI generator does, and
 * writes what it finds as a runtime value. `storage/framework/types/registries.d.ts`
 * reads it with `typeof import(...)`. The list is still produced by a
 * generator; what changed is that it is no longer a type nobody can check
 * against anything - the router can resolve a name out of the same map.
 *
 * Best-effort on purpose. A route registry that fails to load writes an empty
 * map, which the router reads as "no declaration" and falls back to accepting
 * any name - the behaviour before any of this existed. Refusing to generate
 * because one route file threw would be a much worse trade than an unchecked
 * `url()`.
 */
export async function generateRouteNames(): Promise<void> {
  log.info('Generating route names...')

  const namedRoutes = await collectNamedRoutes()

  const entries = Object.entries(namedRoutes)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, routePath]) => `\n  '${name}': '${routePath}',`)
    .join('')

  const contents = `// This file is auto-generated by Stacks. Do not edit this file manually.
//
// Every named route, and the path it resolves to. Read as a type by
// \`storage/framework/types/registries.d.ts\`, so \`url('users.show')\` is checked
// against the routes this application registers - and readable at runtime by
// anything that needs to resolve a name without loading the route table.
//
// For more information, please visit: https://stacksjs.com/docs
export const routeNames = {${entries ? `${entries}\n` : ''}} as const
`

  await storage.writeFile(p.storagePath('framework/auto-imports/routes.ts'), contents)
  log.debug(`[generate:types] Wrote ${Object.keys(namedRoutes).length} named routes`)
}
