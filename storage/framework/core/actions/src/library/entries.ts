import type { ResolvedLibraryPackage } from './packages'
import { relative } from 'node:path'

/**
 * Build the barrel a `functions` package publishes.
 *
 * Specifiers are relative to the entry, which sits beside the copied sources
 * in the package's own `src/`. They used to be absolute paths off the
 * generating machine's home directory — the file is gitignored, so it was
 * regenerated everywhere and the breakage only ever showed up as a build that
 * worked locally and nowhere else.
 *
 * Component packages have no entry here: `buildComponentLibrary` compiles the
 * `.stx` sources and emits its own index, and each generated component
 * registers its custom element on import.
 */
export function functionEntryData(pkg: ResolvedLibraryPackage, stagedSources: string[]): string {
  const lines = [
    `// Generated by \`buddy generate:entries\` for ${pkg.name}. Do not edit.`,
    '',
  ]

  for (const source of stagedSources) {
    // The `.ts` extension is deliberate, not a slip. `transpilePackage`
    // rewrites relative `.ts` specifiers to `.js` on the way into `dist`,
    // so the published barrel says `from './counter.js'`. An extensionless
    // specifier survives the transpile as-is and only resolves under Bun —
    // Node and Vite both reject it, which is a package that installs fine
    // and fails on first import.
    const path = relative(`${pkg.dir}/src`, source)
    const specifier = `./${path}`
    const alias = pkg.aliases[path.replace(/\.ts$/, '')]

    lines.push(alias ? `export * as ${alias} from '${specifier}'` : `export * from '${specifier}'`)
  }

  return `${lines.join('\n')}\n`
}
