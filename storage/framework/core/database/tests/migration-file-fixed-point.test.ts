import { describe, expect, it } from 'bun:test'
import { normalizePostgresMigrationSql } from '../src/migrations'

/**
 * `buddy migrate` writes every Postgres migration back through
 * normalizePostgresMigrationSql(). If that is not a fixed point, a tracked file
 * changes on every run - and the enum guard did: `DO $stacks$ … $stacks$` was
 * split on its inner `;` and re-joined across three lines, then put back on one
 * line by the next pass, so the file flipped between two shapes forever.
 */

const MARKER = '-- qb:generated\n-- @generated by `buddy migrate:regenerate` - edits will be overwritten\n'

const shapes: Record<string, string> = {
  'a bare CREATE TYPE': `${MARKER}CREATE TYPE "leads_stage_type" AS ENUM ('new', 'trial');\n`,
  'a guarded block on one line': `${MARKER}DO $stacks$ BEGIN CREATE TYPE "leads_stage_type" AS ENUM ('new', 'trial'); EXCEPTION WHEN duplicate_object THEN null; END $stacks$;\n`,
  'a guarded block across lines': `${MARKER}DO $stacks$ BEGIN CREATE TYPE "leads_stage_type" AS ENUM ('new', 'trial');\nEXCEPTION WHEN duplicate_object THEN null;\nEND $stacks$;\n`,
  'an ALTER with a constraint': `${MARKER}ALTER TABLE "push_tokens" ADD COLUMN "platform" varchar(20);\nALTER TABLE "push_tokens" ADD CONSTRAINT "push_tokens_user_id_fk" FOREIGN KEY ("user_id") REFERENCES "users" ("id");\n`,
}

describe('normalizePostgresMigrationSql', () => {
  for (const [name, sql] of Object.entries(shapes)) {
    it(`is a fixed point for ${name}`, () => {
      const once = normalizePostgresMigrationSql(sql)
      expect(normalizePostgresMigrationSql(once)).toBe(once)
    })
  }

  it('keeps a guarded block whole and asserts its members once', () => {
    const once = normalizePostgresMigrationSql(shapes['a bare CREATE TYPE']!)
    expect(once).toContain(`DO $stacks$ BEGIN CREATE TYPE "leads_stage_type" AS ENUM ('new', 'trial'); EXCEPTION WHEN duplicate_object THEN null; END $stacks$;`)
    expect(once.match(/ADD VALUE IF NOT EXISTS 'trial'/g)?.length).toBe(1)
  })

  it('leaves a file it has nothing to do with untouched', () => {
    const create = `${MARKER}CREATE TABLE IF NOT EXISTS "leads" (\n  "id" BIGSERIAL PRIMARY KEY\n);\n`
    expect(normalizePostgresMigrationSql(create)).toBe(create)
  })
})
