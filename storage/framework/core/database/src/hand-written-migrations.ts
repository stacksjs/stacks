/**
 * Migrations nobody generated.
 *
 * A Stacks schema is meant to be derived: models first, then
 * `buddy generate:migrations` (or `migrate:regenerate`) writes the SQL and
 * stamps it with `-- qb:generated`. A hand-written migration breaks that chain
 * quietly. The models no longer describe the database, the next regeneration
 * has to preserve the file because nothing can recreate it, and the drift it
 * causes - an index under a name the models do not use, a foreign key the
 * models declare and the file left out - only surfaces when someone compares
 * the live schema with the models.
 *
 * This lists them so `migrate:status` can say so and `buddy migrate --strict`
 * can refuse them. Package migrations are not the app's to regenerate and are
 * never listed.
 */

import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { isPackageMigration } from './package-migrations'

/** The marker every generator writes as the first line of a migration it emits. */
export const QB_GENERATED_MARKER = '-- qb:generated'

/** Whether a migration's SQL starts with a generator's marker. */
export function carriesGeneratedMarker(sql: string): boolean {
  const head = sql.slice(0, 400)
  return head.includes(QB_GENERATED_MARKER) || head.includes('@generated by `buddy migrate:regenerate`')
}

export interface HandWrittenMigrationPolicy {
  /** Allow every hand-written migration. */
  allowAll: boolean
  /** Filenames (or logical names, without the ordinal) allowed individually. */
  allowed: ReadonlySet<string>
}

/**
 * The opt-out, from `database.safety.allowHandWrittenMigrations` or the
 * `DB_ALLOW_HAND_WRITTEN_MIGRATIONS` env var (`1`/`true` allows all; a
 * comma-separated list allows those files).
 */
export function handWrittenMigrationPolicy(configured?: boolean | readonly string[], envValue: string | undefined = process.env.DB_ALLOW_HAND_WRITTEN_MIGRATIONS): HandWrittenMigrationPolicy {
  const env = envValue?.trim()
  if (env) {
    if (/^(?:1|true|yes|on)$/i.test(env))
      return { allowAll: true, allowed: new Set() }
    if (!/^(?:0|false|no|off)$/i.test(env))
      return { allowAll: false, allowed: new Set(env.split(',').map(name => name.trim()).filter(Boolean)) }
  }
  if (configured === true)
    return { allowAll: true, allowed: new Set() }
  return { allowAll: false, allowed: new Set(Array.isArray(configured) ? configured : []) }
}

const logicalName = (file: string): string => file.replace(/^\d+[-_]/, '').replace(/\.sql$/i, '')

/**
 * The app-owned `.sql` files in a corpus directory that carry no generator
 * marker, minus any the policy allows. Sorted, in run order.
 */
export function findHandWrittenMigrations(dir: string, policy: HandWrittenMigrationPolicy = { allowAll: false, allowed: new Set() }): string[] {
  if (policy.allowAll)
    return []

  let files: string[]
  try {
    files = readdirSync(dir).filter(file => file.toLowerCase().endsWith('.sql')).sort()
  }
  catch {
    return []
  }

  return files.filter((file) => {
    if (isPackageMigration(file))
      return false
    if (policy.allowed.has(file) || policy.allowed.has(logicalName(file)))
      return false
    try {
      return !carriesGeneratedMarker(readFileSync(join(dir, file), 'utf8'))
    }
    catch {
      return false
    }
  })
}

/**
 * The configured corpus's hand-written migrations, under the configured
 * policy. Never throws: a check that breaks `migrate` is worse than one that
 * does not run.
 */
export async function handWrittenMigrations(): Promise<{ dir: string, files: string[] }> {
  try {
    const { activeMigrationDirectory } = await import('./migrations')
    const dir = await activeMigrationDirectory()

    let configured: boolean | readonly string[] | undefined
    try {
      const { config, overridesReady } = await import('@stacksjs/config')
      await overridesReady
      configured = (config?.database as { safety?: { allowHandWrittenMigrations?: boolean | string[] } } | undefined)?.safety?.allowHandWrittenMigrations
    }
    catch { /* no config: the env var and the default still apply */ }

    return { dir, files: findHandWrittenMigrations(dir, handWrittenMigrationPolicy(configured)) }
  }
  catch {
    return { dir: '', files: [] }
  }
}
